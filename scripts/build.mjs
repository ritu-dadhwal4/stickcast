#!/usr/bin/env node
// Turn a stickcast project (story.json + voice) into a HyperFrames composition.
// Usage: node build.mjs <project>
// Writes index.html, compositions/captions.html, assets/stick.js, assets/story.js.
// Then: npx hyperframes check --json && npx hyperframes render   (run inside the project)
// (c) Ritu Dadhwal — MIT
import fs from 'node:fs';
import path from 'node:path';
import { args, loadStory, resolveStory, dims, ensureDir, RUNTIME_SRC, jsonForScript } from './lib.mjs';
import { groupWords, captionsComposition } from './captions.mjs';

const a = args();
const dir = path.resolve(a._[0] || '.');
const story = loadStory(dir);
const r = resolveStory(story, dir);
const { W, H } = dims(r.format);
const D = r.duration;
ensureDir(path.join(dir, 'assets'));
ensureDir(path.join(dir, 'compositions'));

fs.writeFileSync(path.join(dir, 'assets/stick.js'), RUNTIME_SRC);
const renderStory = { ...r };
fs.writeFileSync(path.join(dir, 'assets/story.js'), `// generated by stickcast build.mjs from story.json. Edit story.json, then rebuild.\nwindow.STORY = ${jsonForScript(renderStory)};\n`);

const capStyle = (r.captions && r.captions.style) || 'pop';
const groups = capStyle === 'none' ? [] : groupWords(r.scenes, capStyle);
if (groups.length) {
  fs.writeFileSync(path.join(dir, 'compositions/captions.html'), captionsComposition({ groups, style: capStyle, theme: r.theme, format: r.format, W, H, duration: D }));
} else if (fs.existsSync(path.join(dir, 'compositions/captions.html'))) fs.rmSync(path.join(dir, 'compositions/captions.html'));

const hasVoice = fs.existsSync(path.join(dir, 'assets/voice.wav'));
const music = story.music && story.music.src && fs.existsSync(path.join(dir, story.music.src)) ? story.music : null;

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${W}, height=${H}" />
    <title>${(story.title || 'stickcast video').replace(/</g, '')}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: ${W}px; height: ${H}px; overflow: hidden; background: ${r.theme.bg}; }
      #root { position: relative; width: 100%; height: 100%; overflow: hidden; }
      #stage { position: absolute; inset: 0; width: ${W}px; height: ${H}px; display: block; }
      /* keeps the canvas fonts loaded (the canvas draws with these families) */
      #fontwarm { position: absolute; left: 0; top: 0; opacity: 0; font-size: 20px; pointer-events: none; }
      #fontwarm .a { font-family: 'Nunito'; font-weight: 800; }
      #fontwarm .b { font-family: 'Nunito'; font-weight: 900; }
      #fontwarm .c { font-family: 'Archivo Black'; font-weight: 400; }
      #fontwarm .d { font-family: 'Poppins'; font-weight: 900; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${D}" data-width="${W}" data-height="${H}">
      <canvas id="stage" class="clip" data-layout-allow-overflow data-start="0" data-duration="${D}" data-track-index="0" width="${W}" height="${H}"></canvas>
${groups.length ? `      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="${D}" data-track-index="1" data-track-kind="captions" data-width="${W}" data-height="${H}"></div>\n` : ''}${hasVoice ? `      <audio id="voice" class="clip" src="assets/voice.wav" data-start="0" data-track-index="2" data-volume="1"></audio>\n` : ''}${music ? `      <audio id="music" class="clip" src="${music.src}" data-start="0" data-duration="${D}" data-track-index="3" data-volume="${music.volume || 0.12}" data-fade-in="0.6" data-fade-out="1.5"></audio>\n` : ''}      <div id="fontwarm" aria-hidden="true"><span class="a">Aa</span><span class="b">Aa</span><span class="c">Aa</span><span class="d">AA</span></div>
    </div>
    <script src="assets/stick.js"></script>
    <script src="assets/story.js"></script>
    <script>
      const cv = document.getElementById("stage");
      const g = cv.getContext("2d");
      let last = 0;
      function renderAt(t) { last = t; STICK.drawFrame(g, window.STORY, t); }
      const fontsReady = document.fonts && document.fonts.ready ? document.fonts.ready : Promise.resolve();
      window.addEventListener("hf-seek", (e) => {
        renderAt(e.detail.time);
        if (e.detail.waitUntil) e.detail.waitUntil(fontsReady.then(() => renderAt(e.detail.time)));
      });
      renderAt(0);
      fontsReady.then(() => renderAt(last));
      const tl = gsap.timeline({ paused: true });
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`;
fs.writeFileSync(path.join(dir, 'index.html'), html);
console.log(JSON.stringify({ ok: true, dir, duration: D, scenes: r.scenes.length, captions: capStyle, captionGroups: groups.length, voice: hasVoice, music: !!music, format: r.format, theme: r.themeId }, null, 1));
